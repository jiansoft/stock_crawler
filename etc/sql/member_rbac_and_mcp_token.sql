CREATE TABLE IF NOT EXISTS public.member_group (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        character varying(64) NOT NULL UNIQUE
                CHECK (code ~ '^[a-z][a-z0-9_]{1,62}$'),
    name        character varying(128) NOT NULL,
    description text NOT NULL DEFAULT '',
    -- is_root 不可編輯：只有代碼為 root 的群組是 root
    is_root     boolean GENERATED ALWAYS AS (code = 'root') STORED,
    is_system   boolean NOT NULL DEFAULT false,
    -- 家長可指派的群組（2.7 H2）；只有 root 能改。root 群組不可設定；含系統類權限的群組由第 7 段觸發器擋
    household_assignable boolean NOT NULL DEFAULT false
                CHECK (NOT (code = 'root' AND household_assignable)),
    created_at  timestamp with time zone NOT NULL DEFAULT now(),
    updated_at  timestamp with time zone NOT NULL DEFAULT now()
);

-- 既有資料庫補欄位（CREATE TABLE IF NOT EXISTS 不會補）
ALTER TABLE public.member_group
    ADD COLUMN IF NOT EXISTS household_assignable boolean NOT NULL DEFAULT false;

COMMENT ON TABLE public.member_group IS '會員權限群組；root 群組由程式短路放行，不存權限列';

-- 群組代碼建立後不可變更：is_root 由 code 產生，
-- 若能把 'root' 改成別的代碼，第 7 段的觸發器會因為找不到 root 群組而整個失效。
CREATE OR REPLACE FUNCTION public.member_group_protect_code() RETURNS trigger AS $$
BEGIN
    IF NEW.code <> OLD.code THEN
        RAISE EXCEPTION '群組代碼建立後不可變更';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_member_group_protect_code ON public.member_group;
CREATE TRIGGER trg_member_group_protect_code
    BEFORE UPDATE OF code ON public.member_group
    FOR EACH ROW EXECUTE FUNCTION public.member_group_protect_code();

