-- 送達紀錄：不存訊息內容（內容含持股與金額），只記錄送給誰、哪個主題、結果；保留 90 天（清理排程見 4.4）
-- 採「先佔位、再發送、後更新」：若「送出後才寫 sent」，在送出與寫入之間當機，
-- 或兩個排程並行時都會重發。流程見 7.6「去重與紀錄」。
CREATE TABLE IF NOT EXISTS public.member_notify_delivery (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    created_at  timestamp with time zone NOT NULL DEFAULT now(),  -- 佔位時間
    sent_at     timestamp with time zone,                        -- 實際送出時間
    member_id   bigint NOT NULL,
    channel_id  bigint,                                          -- skipped_empty 時為 NULL
    topic       character varying(64) NOT NULL,
    dedup_key   character varying(128) NOT NULL DEFAULT '',      -- 例：holdings.payable:2026-11-10
    -- pending = 已佔位、正在送；sent；failed（可重試，佔位釋放）；
    -- unknown = pending 超過 30 分鐘仍未更新（送出與否不明，不重送）；skipped_empty = 範圍內沒有內容
    status      character varying(16) NOT NULL
                CHECK (status IN ('pending', 'sent', 'failed', 'unknown', 'skipped_empty')),
    error_code  integer
