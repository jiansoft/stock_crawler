-- =============================================================================
-- 7. 至少保留一位啟用中的 root（第二道防線；第一道在 stock_go IAMService）
-- =============================================================================
-- 這個觸發器要避開兩個問題：
--   (a) 不看被異動的那一列：只要資料庫裡沒有啟用中的 root（例如測試庫），任何群組指派的刪改、
--       任何會員的 is_active 更新都會被擋，測試清理假會員會全部失敗。
--   (b) 並行時防不住：兩個交易各移除一位 root，各自檢查時看不到對方尚未提交的刪除，兩邊都通過。
-- 作法：只有「這次異動確實拿走一位啟用中的 root」才檢查；檢查前先鎖住 root 群組那一列，
-- 讓第二個交易等第一個提交後再檢查。READ COMMITTED 下鎖到之後的 SELECT 會取新快照，看得到對方的刪除。
-- SECURITY DEFINER：觸發器延遲到提交時才執行。舊版 PostgreSQL（實測 16）以「提交當下」的角色執行，
-- 維護角色經 SECURITY DEFINER 函式刪除會員時，提交時已換回 stock_go_maint，讀 member_group 會被拒；
-- 新版（實測 19）改以「排入事件時」的角色執行。以擁有者身分執行讓各版本行為一致，呼叫者也不必另外授權。
CREATE OR REPLACE FUNCTION public.member_assert_root_exists() RETURNS trigger AS $$
DECLARE
    root_group_id bigint;
    removes_root  boolean;
BEGIN
    SELECT id INTO root_group_id FROM public.member_group WHERE is_root;
    IF root_group_id IS NULL THEN
        RETURN NULL;   -- 尚未建立 root 群組（建表過程中）
    END IF;

    IF TG_TABLE_NAME = 'member_group_mapping' THEN
        -- 刪除指派、或把指派從 root 改成別的群組（含刪除會員時的 CASCADE）；
        -- DELETE 時 NEW 為 NULL，所以依 TG_OP 分開判斷，不寫在同一個運算式裡
        IF TG_OP = 'DELETE' THEN
            removes_root := OLD.group_id = root_group_id;
        ELSE
            removes_root := OLD.group_id = root_group_id AND NEW.group_id <> root_group_id;
        END IF;
    ELSE
        -- "Member"：啟用中的 root 成員被停用或標記刪除
        removes_root := OLD.is_active AND OLD.deleted_at IS NULL
                        AND (NOT NEW.is_active OR NEW.deleted_at IS NOT NULL)
                        AND EXISTS (SELECT 1 FROM public.member_group_mapping
                                    WHERE member_id = OLD."Id" AND group_id = root_group_id);
    END IF;

    IF NOT removes_root THEN
        RETURN NULL;
    END IF;

    PERFORM 1 FROM public.member_group WHERE id = root_group_id FOR UPDATE;

    IF NOT EXISTS (
        SELECT 1
        FROM public.member_group_mapping AS m
        JOIN public."Member" AS mem
          ON mem."Id" = m.member_id AND mem.is_active AND mem.deleted_at IS NULL
        WHERE m.group_id = root_group_id
    ) THEN
        RAISE EXCEPTION '至少需要保留一位啟用中的 root 成員';
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog;

DROP TRIGGER IF EXISTS trg_member_group_mapping_root ON public.member_group_mapping;
CREATE CONSTRAINT TRIGGER trg_member_group_mapping_root
    AFTER UPDATE OR DELETE ON public.member_group_mapping
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION public.member_assert_root_exists();

DROP TRIGGER IF EXISTS trg_member_active_root ON public."Member";
CREATE CONSTRAINT TRIGGER trg_member_active_root
    AFTER UPDATE OF is_active, deleted_at ON public."Member"
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION public.member_assert_root_exists();

-- 家庭可用的群組不得含系統類權限（2.7 H2；第一道在 IAMService）
CREATE OR REPLACE FUNCTION public.member_group_assert_household_assignable() RETURNS trigger AS $$
DECLARE
    gid bigint;
BEGIN
    -- 用 IF 分開取值：CASE 會同時解析兩個分支，在 member_group 的列上找不到 group_id 而出錯
    IF TG_TABLE_NAME = 'member_group' THEN
        gid := NEW.id;
    ELSE
        gid := NEW.group_id;
    END IF;
    IF EXISTS (
        SELECT 1
        FROM public.member_group AS g
        JOIN public.member_group_permission AS p ON p.group_id = g.id
        WHERE g.id = gid AND g.household_assignable
          AND (p.permission LIKE 'ops.%' OR p.permission IN ('market.edit', 'analysis.run'))
    ) THEN
        RAISE EXCEPTION '家庭可用的群組不得包含系統類權限';
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_member_group_household_assignable ON public.member_group;
CREATE CONSTRAINT TRIGGER trg_member_group_household_assignable
    AFTER INSERT OR UPDATE OF household_assignable ON public.member_group
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION public.member_group_assert_household_assignable();

DROP TRIGGER IF EXISTS trg_member_group_permission_household_assignable ON public.member_group_permission;
CREATE CONSTRAINT TRIGGER trg_member_group_permission_household_assignable
    AFTER INSERT OR UPDATE ON public.member_group_permission
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION public.member_group_assert_household_assignable();

