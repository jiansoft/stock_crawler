    description     text NOT NULL DEFAULT '',
    category        character varying(32) NOT NULL,         -- 畫面分組：dividend、value、chip、fundamental、technical、market、price_trace、system
    -- holdings / personal = 內容依收件者的範圍產生（分送機制相同）；personal 是持股以外的個人資料，例如價格追蹤
    audience        character varying(16) NOT NULL CHECK (audience IN ('system', 'market', 'holdings', 'personal')),
    -- 訂閱需要的權限（stock_go 寫入訂閱時檢查）：portfolio.view、market.view、ops.view、price_trace.view
    required_permission character varying(64) NOT NULL,
    root_only       boolean NOT NULL DEFAULT false,          -- true = 只有 root 群組的會員可訂閱（system.critical）
    default_enabled boolean NOT NULL DEFAULT false,
    sort_order      integer NOT NULL DEFAULT 0
