-- 會員綁定的通知管道；目前只有 telegram，欄位保留擴充其他管道的空間
CREATE TABLE IF NOT EXISTS public.member_notify_channel (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id       bigint NOT NULL REFERENCES public."Member"("Id") ON DELETE CASCADE,
    kind            character varying(16) NOT NULL CHECK (kind IN ('telegram')),
    address         character varying(64) NOT NULL,          -- telegram 為聊天室的 chat_id
    -- bind = 會員以一次性連結綁定（只允許私人聊天）；legacy_config = 設定檔 bot.telegram.allowed 轉入的既有管道
    source          character varying(16) NOT NULL DEFAULT 'bind' CHECK (source IN ('bind', 'legacy_config')),
    chat_type       character varying(16) NOT NULL DEFAULT 'private' CHECK (chat_type IN ('private', 'group')),
    display_name    character varying(128) NOT NULL DEFAULT '',
    verified_at     timestamp with time zone NOT NULL DEFAULT now(),
    enabled         boolean NOT NULL DEFAULT true,
    disabled_reason character varying(32) NOT NULL DEFAULT '', -- blocked_by_user、chat_not_found、manual
    last_ok_at      timestamp with time zone,
    fail_count      integer NOT NULL DEFAULT 0,
    UNIQUE (kind, address),     -- 一個聊天室只能綁給一位會員
    -- 群組聊天室只能來自設定檔轉入（Eddie 既有的私人群組），會員自行綁定一律是私人聊天
    CHECK (chat_type = 'private' OR source = 'legacy_config')
);

-- 每位會員每種管道最多一個「自行綁定」的聊天室；設定檔轉入的不受此限。
-- 若用 UNIQUE (member_id, kind)，會讓 Eddie 的兩個既有聊天室（私人聊天 + 私人群組）無法同時登記。
CREATE UNIQUE INDEX IF NOT EXISTS idx_member_notify_channel_bind
    ON public.member_notify_channel (member_id, kind)
    WHERE source = 'bind';

