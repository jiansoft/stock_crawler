//! Data API 的路由註冊。
//!
//! `/api/v1` 下除健康檢查外一律套用 Bearer middleware；Swagger UI 與
//! OpenAPI JSON 不受驗證保護，方便內網服務直接產生 client。

use axum::{Router, middleware};
use utoipa::OpenApi;
use utoipa_swagger_ui::SwaggerUi;

use super::openapi::ApiDoc;
use super::{auth, handlers};

/// 建立 `/api/v1` 路由與不受驗證保護的 Swagger/OpenAPI 文件入口。
pub(crate) fn router() -> Router {
    let protected = Router::new()
        .route(
            "/stocks/search",
            axum::routing::get(handlers::search_stocks),
        )
        .route(
            "/stocks/{symbol}/latest-quote",
            axum::routing::get(handlers::latest_quote),
        )
        .route(
            "/stocks/{symbol}/price-history",
            axum::routing::get(handlers::price_history),
        )
        .route(
            "/stocks/{symbol}/profile",
            axum::routing::get(handlers::stock_profile),
        )
        .route(
            "/stocks/{symbol}/realtime-snapshot",
            axum::routing::get(handlers::realtime_snapshot),
        )
        .route(
            "/stocks/{symbol}/monthly-revenues",
            axum::routing::get(handlers::monthly_revenues),
        )
        .route(
            "/stocks/{symbol}/financial-statements",
            axum::routing::get(handlers::financial_statements),
        )
        .route(
            "/stocks/{symbol}/financial-reports",
            axum::routing::get(handlers::financial_reports),
        )
        .route(
            "/stocks/{symbol}/financial-health",
            axum::routing::get(handlers::financial_health),
        )
        .route(
            "/stocks/{symbol}/dividend-fill",
            axum::routing::get(handlers::dividend_fill),
        )
        .route(
            "/stocks/{symbol}/dividends",
            axum::routing::get(handlers::dividend_history),
        )
        .route(
            "/stocks/{symbol}/chip",
            axum::routing::get(handlers::stock_chip),
        )
        .route(
            "/stocks/{symbol}/valuation",
            axum::routing::get(handlers::stock_valuation),
        )
        .route(
            "/portfolio/summary",
            axum::routing::get(handlers::portfolio_summary),
        )
        .route(
            "/portfolio/history",
            axum::routing::get(handlers::portfolio_history),
        )
        .route(
            "/portfolio/chip",
            axum::routing::get(handlers::portfolio_chip),
        )
        .route(
            "/portfolio/dividend-fill",
            axum::routing::get(handlers::portfolio_dividend_fill),
        )
        .route(
            "/portfolio/dividend-forecast",
            axum::routing::get(handlers::dividend_forecast),
        )
        .route(
            "/stocks/{symbol}/valuation-band",
            axum::routing::get(handlers::stock_valuation_band),
        )
        .route(
            "/stocks/{symbol}/technicals",
            axum::routing::get(handlers::stock_technicals),
        )
        .route(
            "/stocks/{symbol}/signals",
            axum::routing::get(handlers::stock_signals),
        )
        .route(
            "/stocks/{symbol}/timeline",
            axum::routing::get(handlers::stock_timeline),
        )
        .route(
            "/stocks/{symbol}/relative-strength",
            axum::routing::get(handlers::relative_strength_history),
        )
        .route(
            "/stocks/{symbol}/peers",
            axum::routing::get(handlers::stock_peers),
        )
        .route(
            "/market/breadth",
            axum::routing::get(handlers::market_breadth),
        )
        .route(
            "/market/dividend-yield-ranking",
            axum::routing::get(handlers::dividend_yield_ranking),
        )
        .route(
            "/stocks/screen/backtest",
            axum::routing::get(handlers::screen_backtest),
        )
        .route(
            "/stocks/screen/backtest/offsets",
            axum::routing::get(handlers::screen_backtest_offsets),
        )
        .route(
            "/stocks/screen/backtest/frontier",
            axum::routing::get(handlers::screen_backtest_frontier),
        )
        .route(
            "/strategy-presets",
            axum::routing::get(handlers::strategy_presets),
        )
        .route(
            "/strategy-presets/{name}/track",
            axum::routing::get(handlers::strategy_track),
        )
        .route(
            "/stocks/screen/backtest/walk-forward",
            axum::routing::get(handlers::screen_backtest_walk_forward),
        )
        .route(
            "/stocks/screen/backtest/attribution",
            axum::routing::get(handlers::screen_backtest_attribution),
        )
        .route(
            "/stocks/screen",
            axum::routing::get(handlers::screen_stocks),
        )
        .route(
            "/market/index-history",
            axum::routing::get(handlers::market_index_history),
        )
        .route(
            "/market/dividend-calendar",
            axum::routing::get(handlers::dividend_calendar),
        )
        .route(
            "/market/qfii-holding-ranking",
            axum::routing::get(handlers::qfii_holding_ranking),
        )
        .route(
            "/market/industries",
            axum::routing::get(handlers::industry_performance),
        )
        .route(
            "/market/movers",
            axum::routing::get(handlers::market_movers),
        )
        .route(
            "/market/signals",
            axum::routing::get(handlers::market_signals),
        )
        .route(
            "/market/signals/performance",
            axum::routing::get(handlers::signal_performance),
        )
        .route(
            "/market/relative-strength",
            axum::routing::get(handlers::relative_strength),
        )
        .route(
            "/market/industry-strength",
            axum::routing::get(handlers::industry_strength),
        )
        .route(
            "/market/institutional-flow",
            axum::routing::get(handlers::institutional_flow),
        )
        .route(
            "/market/institutional-streak/performance",
            axum::routing::get(handlers::institutional_streak_performance),
        )
        .route(
            "/market/industry-flow",
            axum::routing::get(handlers::industry_flow),
        )
        .route(
            "/market/margin-ranking",
            axum::routing::get(handlers::margin_ranking),
        )
        .route(
            "/market/regime",
            axum::routing::get(handlers::market_regime),
        )
        .route(
            "/market/valuation",
            axum::routing::get(handlers::market_valuation),
        )
        .route("/etfs", axum::routing::get(handlers::list_etfs))
        .route("/etfs/compare", axum::routing::get(handlers::compare_etfs))
        .route("/etfs/{symbol}", axum::routing::get(handlers::etf_detail))
        .route(
            "/market/cagr-ranking",
            axum::routing::get(handlers::cagr_ranking),
        )
        .route(
            "/market/cagr-ranking/{stock_symbol}",
            axum::routing::get(handlers::cagr_by_symbol),
        )
        .layer(middleware::from_fn(auth::require_bearer_key));
    Router::new()
        .nest(
            "/api/v1",
            protected.route("/healthz", axum::routing::get(handlers::healthz)),
        )
        .merge(SwaggerUi::new("/swagger-ui").url("/api-docs/openapi.json", ApiDoc::openapi()))
}

